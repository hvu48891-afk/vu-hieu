-- 1. Create Classrooms table
CREATE TABLE IF NOT EXISTS public.classrooms (
    id TEXT PRIMARY KEY,
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    building TEXT,
    floor INTEGER,
    capacity INTEGER,
    total_power_w NUMERIC DEFAULT 0,
    current_a NUMERIC DEFAULT 0,
    temperature NUMERIC DEFAULT 25.0,
    humidity NUMERIC DEFAULT 60.0,
    is_vacant BOOLEAN DEFAULT false,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    data JSONB
);

-- 2. Create Hardware Telemetry / Command Logs table
CREATE TABLE IF NOT EXISTS public.hardware_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic TEXT NOT NULL,
    payload TEXT NOT NULL,
    direction TEXT NOT NULL,
    type TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now())
);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.classrooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.hardware_logs ENABLE ROW LEVEL SECURITY;

-- 4. Create Policies to allow read and write from client app
CREATE POLICY "Allow public read classrooms" 
ON public.classrooms FOR SELECT 
USING (true);

CREATE POLICY "Allow public insert/update classrooms" 
ON public.classrooms FOR ALL 
USING (true) 
WITH CHECK (true);

CREATE POLICY "Allow public read hardware_logs" 
ON public.hardware_logs FOR SELECT 
USING (true);

CREATE POLICY "Allow public insert hardware_logs" 
ON public.hardware_logs FOR INSERT 
WITH CHECK (true);
